#!/bin/bash
# Renders every wallpaper into out/: the side-by-side clip (what Sparky Stereo OS plays), a red/cyan
# anaglyph preview for any ordinary player, and SHA256SUMS. Each clip carries its provenance in
# its tags: title, author, licence, source repository, script and commit.
# Needs Python 3 with numpy, and an ffmpeg with libx264 and the stereo3d filter.
#   ./build.sh                 all wallpapers
#   ./build.sh particles       just one
#   PYTHON=/path/to/python FFMPEG=/usr/bin/ffmpeg ./build.sh
set -euo pipefail
cd "$(dirname "$0")"
PYTHON=${PYTHON:-python3}
FFMPEG=${FFMPEG:-ffmpeg}
REPO=https://github.com/halverneus/stereo-wallpapers
commit=$(git rev-parse --short=12 HEAD 2>/dev/null || echo unknown)
git diff --quiet HEAD -- 2>/dev/null || commit="$commit+local-changes"
mkdir -p out

declare -A TITLE=(
    [particles]="Particles: a slow, deep field of drifting motes"
    [waves]="Waves: a softly lit grid swelling in depth"
)
names=("$@"); [ ${#names[@]} -gt 0 ] || names=(particles waves)

for name in "${names[@]}"; do
    [ -n "${TITLE[$name]:-}" ] || { echo "no wallpaper called $name" >&2; exit 1; }
    echo "== $name (from make-$name.py at $commit)"
    "$PYTHON" "make-$name.py" | "$FFMPEG" -hide_banner -loglevel error -y \
        -f rawvideo -pix_fmt rgb24 -s 3840x1080 -r 30 -i - \
        -c:v libx264 -preset slow -crf 18 -pix_fmt yuv420p -x264-params aq-mode=3 \
        -metadata title="${TITLE[$name]}" \
        -metadata artist="Jeromy Streets" \
        -metadata copyright="Public domain: CC0 1.0 Universal, https://creativecommons.org/publicdomain/zero/1.0/" \
        -metadata license="CC0-1.0" \
        -metadata url="$REPO" \
        -metadata comment="Generated by make-$name.py, $REPO, commit $commit. Side-by-side full width, left eye on the left; 12 s seamless loop; everything sits behind the screen (+4 to +40 px disparity at 1920 px per eye). Made by Jeromy Streets with Claude (Anthropic)." \
        -metadata:s:v stereo_mode=left_right \
        "out/$name-sbs.mkv"
    "$FFMPEG" -hide_banner -loglevel error -y -i "out/$name-sbs.mkv" \
        -vf stereo3d=sbsl:arcd -c:v libx264 -crf 18 -pix_fmt yuv420p -map_metadata 0 \
        "out/$name-anaglyph.mp4"
done
(cd out && sha256sum -- *.mkv *.mp4 > SHA256SUMS)
cat out/SHA256SUMS
